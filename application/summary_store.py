"""Define persistence of immutable summaries and mandatory read authorization."""

from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from .risk_summary import ProjectRiskSummary


@dataclass(frozen=True, slots=True)
class SavedSummary:
    """Bind a summary to a run, project, recipient and aware calculation time.

    The result ID is generated by storage. project_timezone records the IANA
    zone used to calculate the result, or None when the source did not record
    one; it is never guessed. Example: store.save_summary('run-1', project_id=3,
    recipient_id=7, checked_at=now, summary=result) returns a SavedSummary
    carrying the immutable result and its identity.
    """

    result_id: str
    run_id: str
    project_id: int
    recipient_id: int
    checked_at: datetime
    summary: ProjectRiskSummary
    project_timezone: str | None = None


type SummaryAuthorizer = Callable[[SavedSummary], bool]


class SummaryStore(Protocol):
    """Save summaries and expose them only after current access is confirmed.

    Example: store: SummaryStore = SQLiteStateStore(path).
    """

    def save_summary(
        self, run_id: str, *, project_id: int, recipient_id: int,
        checked_at: datetime, summary: ProjectRiskSummary,
        project_timezone: str | None = None,
    ) -> SavedSummary:
        """Return a persisted immutable result; an identical retry returns the same ID.

        A different payload, calculation time or recorded project timezone for
        the same run/project/recipient is a conflict. Example:
        store.save_summary('run-1', project_id=3, recipient_id=7,
        checked_at=now, summary=result, project_timezone='Asia/Tokyo') returns
        the saved result.
        """
        ...

    def get_summary(
        self, result_id: str, *, project_id: int, recipient_id: int, authorize: SummaryAuthorizer,
    ) -> SavedSummary | None:
        """Return a result only for its recipient and currently authorized scope.

        The server supplies trusted identity and an authorizer for the whole
        result: membership/manager role, companies, records, fields, assignees
        and the evidence behind each reason. False or SummaryReadError means
        no result, including no rows, status or aggregate counts. Unexpected
        checker errors become StateStoreError without raw details. No permissive
        default is provided. Example: store.get_summary('id', project_id=3,
        recipient_id=7, authorize=server_access_check) returns None on denial.
        """
        ...
